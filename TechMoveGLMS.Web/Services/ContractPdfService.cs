using System;
using System.IO;
using System.Threading.Tasks;
using Microsoft.AspNetCore.Http;

namespace TechMoveGLMS.Web.Services;

public sealed class ContractPdfService
{
    public const long MaxFileSize = 5 * 1024 * 1024; // 5 MB

    private readonly string _storagePath;

    public ContractPdfService(string storagePath)
    {
        if (string.IsNullOrWhiteSpace(storagePath))
        {
            throw new ArgumentException(
                "A PDF storage path is required.",
                nameof(storagePath));
        }

        _storagePath = Path.GetFullPath(storagePath);
    }

    public static bool IsValidPdf(IFormFile? file)
    {
        if (file is null || file.Length <= 0 ||
            file.Length > MaxFileSize)
        {
            return false;
        }

        if (!string.Equals(
                Path.GetExtension(file.FileName),
                ".pdf",
                StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        // Check the PDF signature instead of trusting the extension.
        using var stream = file.OpenReadStream();

        if (stream.Length < 5)
        {
            return false;
        }

        Span<byte> signature = stackalloc byte[5];

        var bytesRead = stream.Read(signature);

        return bytesRead == 5 &&
               signature[0] == (byte)'%' &&
               signature[1] == (byte)'P' &&
               signature[2] == (byte)'D' &&
               signature[3] == (byte)'F' &&
               signature[4] == (byte)'-';
    }

    public async Task<string> SaveAsync(IFormFile file)
    {
        if (!IsValidPdf(file))
        {
            throw new InvalidDataException(
                "The uploaded file must be a valid PDF no larger than 5 MB.");
        }

        Directory.CreateDirectory(_storagePath);

        // Never use the original filename as the stored filename.
        var storedFileName = $"{Guid.NewGuid():N}.pdf";
        var fullPath = Path.Combine(_storagePath, storedFileName);

        await using var destination = new FileStream(
            fullPath,
            FileMode.CreateNew,
            FileAccess.Write,
            FileShare.None,
            bufferSize: 81920,
            useAsync: true);

        await file.CopyToAsync(destination);

        return storedFileName;
    }

    public async Task<Stream?> OpenReadAsync(string storedFileName)
    {
        // Only accept filenames generated by this service.
        if (string.IsNullOrWhiteSpace(storedFileName) ||
            !storedFileName.EndsWith(
                ".pdf",
                StringComparison.OrdinalIgnoreCase) ||
            !Guid.TryParseExact(
                Path.GetFileNameWithoutExtension(storedFileName),
                "N",
                out _))
        {
            return null;
        }

        var fullPath = Path.Combine(_storagePath, storedFileName);

        if (!File.Exists(fullPath))
        {
            return null;
        }

        return await Task.FromResult<Stream>(
            new FileStream(
                fullPath,
                FileMode.Open,
                FileAccess.Read,
                FileShare.Read,
                bufferSize: 81920,
                useAsync: true));
    }


    public Task DeleteAsync(string storedFileName)
{
    if (string.IsNullOrWhiteSpace(storedFileName) ||
        !storedFileName.EndsWith(
            ".pdf",
            StringComparison.OrdinalIgnoreCase) ||
        !Guid.TryParseExact(
            Path.GetFileNameWithoutExtension(storedFileName),
            "N",
            out _))
    {
        return Task.CompletedTask;
    }

    var fullPath = Path.Combine(_storagePath, storedFileName);

    if (File.Exists(fullPath))
    {
        File.Delete(fullPath);
    }

    return Task.CompletedTask;
}
}